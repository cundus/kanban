import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const projectRoot = fileURLToPath(new URL('../', import.meta.url));
const server = spawn(process.execPath, ['node_modules/vite/bin/vite.js', '--host', '127.0.0.1', '--port', '5183', '--strictPort'], { cwd: projectRoot, stdio: ['ignore', 'pipe', 'pipe'], windowsHide: true });
await new Promise((resolve, reject) => {
  const timer = setTimeout(() => { server.kill(); reject(new Error('Vite startup timed out')); }, 20000);
  server.stdout.on('data', data => { if (data.toString().includes('Local:')) { clearTimeout(timer); resolve(); } });
  server.once('error', error => { clearTimeout(timer); reject(error); });
  server.once('exit', code => { clearTimeout(timer); reject(new Error('Vite exited: ' + code)); });
});
const browser = await chromium.launch().catch(error => { server.kill(); throw error; });
const page = await browser.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.route('**/rest/v1/**', route => route.fulfill({ contentType: 'application/json', body: '[]' }));
try {
  await page.goto('http://127.0.0.1:5183/tests/fixtures/description-editor.html?images=multiple');
  const thumbnail = page.getByRole('button', { name: 'View image 1', exact: true });
  await thumbnail.waitFor({ timeout: 2000 });
  await thumbnail.click();
  let viewer = page.getByRole('dialog', { name: 'Image 1 of 3', exact: true });
  await viewer.waitFor();
  const image = viewer.getByRole('img', { name: 'Task image 1', exact: true });
  await image.waitFor();
  await page.waitForFunction(() => document.querySelector('img[alt="Task image 1"]')?.naturalWidth === 1600);
  await viewer.getByRole('button', { name: 'Next image', exact: true }).click();
  viewer = page.getByRole('dialog', { name: 'Image 2 of 3', exact: true });
  await viewer.waitFor();
  await page.keyboard.press('ArrowLeft');
  await page.getByRole('dialog', { name: 'Image 1 of 3', exact: true }).waitFor();
  await page.keyboard.press('ArrowLeft');
  viewer = page.getByRole('dialog', { name: 'Image 3 of 3', exact: true });
  await viewer.getByRole('alert').waitFor();
  await viewer.getByRole('button', { name: 'Next image', exact: true }).click();
  await page.getByRole('dialog', { name: 'Image 1 of 3', exact: true }).waitFor();
  await page.keyboard.press('Escape');
  await page.waitForFunction(() => document.querySelectorAll('[data-slot="dialog-content"]').length === 1);
  assert.equal(await page.locator('[data-slot="dialog-content"]').count(), 1, 'Escape leaves task dialog open');
  assert.equal(await thumbnail.evaluate(el => el === document.activeElement), true, 'focus returns to opening thumbnail');
  await thumbnail.focus();
  await page.keyboard.press('Enter');
  viewer = page.getByRole('dialog', { name: 'Image 1 of 3', exact: true });
  await viewer.waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await viewer.getByRole('button', { name: 'Next image', exact: true }).click();
  viewer = page.getByRole('dialog', { name: 'Image 2 of 3', exact: true });
  await page.waitForFunction(() => document.querySelector('img[alt="Task image 2"]')?.naturalHeight === 1600);
  const dimensions = await viewer.getByRole('img', { name: 'Task image 2', exact: true }).boundingBox();
  assert.ok(dimensions.width <= 390 && dimensions.height <= 844, 'portrait fits mobile viewport');
  assert.ok(Math.abs(dimensions.width / dimensions.height - 900 / 1600) < 0.01, 'portrait preserves aspect ratio');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: join(tmpdir(), 'kanban-image-viewer-mobile.png') });
  await viewer.getByRole('button', { name: 'Close', exact: true }).click();
  await page.waitForFunction(() => document.querySelectorAll('[data-slot="dialog-content"]').length === 1);
  await thumbnail.click();
  await page.evaluate(() => window.removeFirstViewerImage());
  await page.waitForFunction(() => document.querySelectorAll('[data-slot="dialog-content"]').length === 1);
  assert.equal(await page.getByRole('button', { name: /^View image / }).count(), 2, 'other images remain after the active image is removed');
  await page.getByRole('button', { name: 'View image 1', exact: true }).click();
  await page.evaluate(() => window.switchEditorTask('Different task'));
  await page.waitForFunction(() => document.querySelectorAll('[data-slot="dialog-content"]').length === 1);
  assert.equal(await page.getByRole('button', { name: /^View image / }).count(), 0, 'task switch resets the viewer and gallery');
  await page.goto('http://127.0.0.1:5183/tests/fixtures/description-editor.html?images=single');
  await page.getByRole('button', { name: 'View image 1', exact: true }).click();
  viewer = page.getByRole('dialog', { name: 'Image 1 of 1', exact: true });
  await viewer.waitFor();
  assert.equal(await viewer.getByRole('button', { name: 'Next image' }).count(), 0, 'single image has no navigation');
  assert.equal(await viewer.getByRole('button', { name: 'Previous image' }).count(), 0);
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ passed: true, checks: ['thumbnail opens nested modal', 'button and keyboard navigation with wrap', 'broken image feedback', 'Escape closes only viewer', 'focus restoration', 'keyboard activation', 'portrait fits mobile', 'removed image closes viewer', 'single image'], pageErrors: errors }));
} finally { await browser.close(); server.kill(); }
