import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const projectRoot = fileURLToPath(new URL('../', import.meta.url));
const server = spawn(process.execPath, ['node_modules/vite/bin/vite.js', '--host', '127.0.0.1', '--port', '5182', '--strictPort'], { cwd: projectRoot, stdio: ['ignore', 'pipe', 'pipe'], windowsHide: true });
await new Promise((resolve, reject) => {
  const timer = setTimeout(() => { server.kill(); reject(new Error('Vite startup timed out')); }, 20000);
  server.stdout.on('data', data => { if (data.toString().includes('Local:')) { clearTimeout(timer); resolve(); } });
  server.once('error', error => { clearTimeout(timer); reject(error); });
  server.once('exit', code => { clearTimeout(timer); reject(new Error('Vite exited: ' + code)); });
});
const browser = await chromium.launch().catch(error => { server.kill(); throw error; });
const page = await browser.newPage();
let failNext = false;
let saveDelay = 0;
const writes = [];
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.route('**/rest/v1/**', async route => {
  if (route.request().method() === 'PATCH') {
    const body = route.request().postDataJSON();
    writes.push(body);
    const fail = failNext;
    failNext = false;
    await new Promise(resolve => setTimeout(resolve, saveDelay));
    return route.fulfill({ status: fail ? 500 : 204, ...(fail ? { contentType: 'application/json', body: JSON.stringify({ message: 'Save failed' }) } : {}) });
  }
  return route.fulfill({ contentType: 'application/json', body: '[]' });
});
try {
  await page.goto('http://127.0.0.1:5182/tests/fixtures/description-editor.html');
  const editor = page.locator('.ProseMirror[contenteditable="true"]');
  const save = page.getByRole('button', { name: 'Save description', exact: true });
  await editor.waitFor();
  assert.equal(await save.count(), 0, 'loading the initial document is not an edit');
  await editor.click();
  await page.keyboard.press('Control+End');
  await page.keyboard.type(' first edit');
  await save.waitFor({ timeout: 1500 });
  await save.click();
  await page.waitForFunction(() => ![...document.querySelectorAll('button')].some(el => el.textContent === 'Save description'));
  assert.match(writes.at(-1).description_md, /first edit/);
  await editor.click();
  await page.keyboard.press('Control+End');
  await page.keyboard.type(' latest characters');
  await save.click();
  await page.waitForFunction(() => ![...document.querySelectorAll('button')].some(el => el.textContent === 'Save description'));
  assert.match(writes.at(-1).description_md, /latest characters/);
  saveDelay = 350;
  await editor.click();
  await page.keyboard.type(' before save');
  const pendingSave = page.waitForResponse(response => response.request().method() === 'PATCH');
  await save.click();
  await editor.click();
  await page.keyboard.press('Control+End');
  await page.keyboard.type(' while saving');
  await pendingSave;
  assert.equal(await save.isVisible(), true, 'edits made during save remain dirty');
  saveDelay = 0;
  await save.click();
  await page.waitForFunction(() => ![...document.querySelectorAll('button')].some(el => el.textContent === 'Save description'));
  assert.match(writes.at(-1).description_md, /while saving/);
  await editor.click();
  await page.keyboard.type(' retry content');
  failNext = true;
  await save.click();
  await page.getByText('Gagal menyimpan deskripsi.', { exact: true }).waitFor();
  assert.equal(await save.isVisible(), true);
  await save.click();
  await page.waitForFunction(() => ![...document.querySelectorAll('button')].some(el => el.textContent === 'Save description'));
  assert.match(writes.at(-1).description_md, /retry content/);
  const largeDescription = Array.from({ length: 200 }, (_, index) => `Paragraph ${index}: **formatted text**, [link](https://example.test), and more content.`).join('\n\n');
  await page.evaluate(description => window.switchEditorTask(description), largeDescription);
  await page.waitForFunction(() => document.querySelector('.ProseMirror')?.textContent.includes('Paragraph 199'));
  assert.equal(await save.count(), 0, 'switching tasks resets dirty state');
  await editor.click();
  await page.keyboard.press('Control+End');
  await page.keyboard.type(' first burst');
  await save.waitFor();
  const commitsBefore = await page.evaluate(() => window.editorMetrics.commits);
  const writesBefore = writes.length;
  for (let index = 0; index < 6; index++) {
    await page.keyboard.type(` typing burst ${index}`);
    await page.waitForTimeout(250);
  }
  const typingCommits = await page.evaluate(() => window.editorMetrics.commits) - commitsBefore;
  assert.ok(typingCommits <= 1, `typing in a large document should not repeatedly render the modal: ${typingCommits} commits`);
  assert.equal(writes.length, writesBefore, 'typing does not write to the server');
  await page.evaluate(description => window.refreshEditorTask(description), largeDescription);
  assert.match(await editor.textContent(), /typing burst 5/, 'same task cache refresh must preserve local edits');
  assert.equal(await save.isVisible(), true, 'cache refresh must not clear dirty state');
  await save.click();
  await page.waitForFunction(() => ![...document.querySelectorAll('button')].some(el => el.textContent === 'Save description'));
  assert.match(writes.at(-1).description_md, /typing burst 5/);
  saveDelay = 350;
  await editor.click();
  await page.keyboard.press('Control+End');
  await page.keyboard.type(' save on previous task');
  const oldTaskSave = page.waitForResponse(response => response.request().method() === 'PATCH');
  await save.click();
  await page.evaluate(() => window.switchEditorTask('New task description'));
  await page.waitForFunction(() => document.querySelector('.ProseMirror')?.textContent.includes('New task description'));
  await editor.click();
  await page.keyboard.press('Control+End');
  await page.keyboard.type(' new unsaved edit');
  await oldTaskSave;
  assert.equal(await save.isVisible(), true, 'old task save must not clear new task edits');
  saveDelay = 0;
  await save.click();
  await page.waitForFunction(() => ![...document.querySelectorAll('button')].some(el => el.textContent === 'Save description'));
  assert.match(writes.at(-1).description_md, /New task description.*new unsaved edit/);
  await editor.click();
  await page.keyboard.press('Control+A');
  await page.keyboard.press('Backspace');
  await save.click();
  await page.waitForFunction(() => ![...document.querySelectorAll('button')].some(el => el.textContent === 'Save description'));
  assert.equal(writes.at(-1).description_md, null, 'clearing description saves null');
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ passed: true, checks: ['first edit enables Save', 'immediate save contains latest characters', 'typing during save remains dirty', 'failed save preserves changes for retry', 'large document avoids repeated React renders', 'task switching and stale save callbacks', 'clear description'], typingCommits, writes: writes.length, pageErrors: errors }));
} finally { await browser.close(); server.kill(); }
